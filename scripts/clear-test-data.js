// Clears accumulated test data, keeping the catalogue and settings.
//
//   npm run clear-test-data          # show what would go, change nothing
//   npm run clear-test-data -- --yes # actually delete
//
// Dry run by default. Deleting is the kind of thing that should have to be
// asked for twice.
//
// Refuses to run against anything but upcell_development, so pointing .env at
// production and running this out of habit cannot wipe real orders.
require("dotenv").config();

const fs = require("fs");
const path = require("path");
const mongoose = require("mongoose");

const ONLY_DATABASE = "upcell_development";
const CONFIRMED = process.argv.includes("--yes");

// Everything here is generated by using the site: orders placed, messages the
// bank sent back, forms submitted, pages viewed.
const CLEAR = [
  ["orders", "customer orders"],
  ["paymenteventlogs", "bank payment messages"],
  ["notifications", "admin notifications"],
  ["tradeinrequests", "trade-in requests"],
  ["auditlogs", "admin action history"],
  ["analytics_events", "page and click tracking"],
  ["contactsubmissions", "contact form messages"],
  ["addforms", "wholesale enquiries"],
  ["chat_conversations", "chat history"],
  ["chat_daily_usages", "chat usage counters"],
];

// The catalogue and the settings. Listed explicitly so a careless edit to
// CLEAR is caught by the guard below rather than quietly obeyed.
const MUST_SURVIVE = [
  ["singlevariations", "every device for sale"],
  ["parentproducts", "product families"],
  ["shopcategories", "shop categories"],
  ["availablecatagories", "category list"],
  ["monthlysells", "monthly sold counter"],
  ["newslettersubscribers", "newsletter sign-ups"],
  ["emailconfigs", "email on/off switches"],
  ["chat_settings", "chat configuration"],
];

(async () => {
  const url = process.env.MONGODB_URL || "";

  if (!url.includes(ONLY_DATABASE)) {
    console.error(
      `\nRefusing to run: MONGODB_URL does not point at ${ONLY_DATABASE}.` +
      `\nThis script only ever clears the development database.\n`
    );
    process.exit(1);
  }

  const overlap = CLEAR.map(([c]) => c).filter((c) =>
    MUST_SURVIVE.some(([k]) => k === c)
  );
  if (overlap.length) {
    console.error("Refusing to run: would delete a protected collection: " + overlap);
    process.exit(1);
  }

  await mongoose.connect(url, { serverSelectionTimeoutMS: 15000 });
  const db = mongoose.connection;

  // Always write a backup, even on a dry run — it costs a second and it is the
  // difference between a mistake being annoying and being permanent.
  const dump = {};
  let backedUp = 0;
  for (const [name] of [...CLEAR, ...MUST_SURVIVE]) {
    dump[name] = await db.collection(name).find({}).toArray();
    backedUp += dump[name].length;
  }

  const dir = path.join(__dirname, "..", "backups");
  fs.mkdirSync(dir, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
  const file = path.join(dir, `upcell_development-${stamp}.json`);
  fs.writeFileSync(file, JSON.stringify(dump, null, 1));

  console.log(`\nBackup written: ${path.relative(process.cwd(), file)}`);
  console.log(`  ${backedUp} rows, ${(fs.statSync(file).size / 1024 / 1024).toFixed(1)} MB\n`);

  console.log(CONFIRMED ? "CLEARING" : "DRY RUN — nothing will be deleted");
  console.log("-".repeat(58));

  let total = 0;
  for (const [name, description] of CLEAR) {
    const count = await db.collection(name).countDocuments({});
    if (!count) {
      console.log("  " + description.padEnd(26) + "already empty");
      continue;
    }
    if (CONFIRMED) {
      const { deletedCount } = await db.collection(name).deleteMany({});
      total += deletedCount;
      console.log("  " + description.padEnd(26) + "deleted " + deletedCount);
    } else {
      total += count;
      console.log("  " + description.padEnd(26) + "would delete " + count);
    }
  }

  console.log("\nKEEPING");
  console.log("-".repeat(58));
  for (const [name, description] of MUST_SURVIVE) {
    console.log(
      "  " + description.padEnd(26) +
      (await db.collection(name).countDocuments({})) + " rows"
    );
  }

  console.log("\n" + (CONFIRMED ? "deleted " : "would delete ") + total + " rows");
  if (!CONFIRMED) console.log("Run again with  -- --yes  to actually delete.\n");

  await mongoose.disconnect();
})().catch((error) => {
  console.error("Failed:", error.message);
  process.exit(1);
});
