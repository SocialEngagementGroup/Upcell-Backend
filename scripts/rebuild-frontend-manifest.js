#!/usr/bin/env node
/**
 * Rewrites Frontend/src/data/productImageManifest.js to reference Cloudinary
 * public_ids instead of local /product-images/... paths.
 *
 *   node scripts/rebuild-frontend-manifest.js [--dry-run]
 *
 * Reads scripts/cloudinary-manifest.json (produced by
 * migrate-images-to-cloudinary.js). Every entry must map, or the script
 * refuses to write — a partial manifest would silently drop images from the
 * catalogue rather than fail loudly.
 *
 * The matching fields (category, model, file, originalPath) are preserved
 * exactly, because resolveProductImage() scores against them. Only the
 * delivery reference changes: `url` becomes `publicId`.
 */
const fs = require("fs");
const path = require("path");

const MAPPING = path.join(__dirname, "cloudinary-manifest.json");
const MANIFEST = path.resolve(
  __dirname, "..", "..", "Frontend", "src", "data", "productImageManifest.js"
);

const DRY_RUN = process.argv.includes("--dry-run");

const { mapping } = JSON.parse(fs.readFileSync(MAPPING, "utf8"));
const lookup = (url) => mapping[String(url).replace(/^\//, "")]?.publicId;

// The manifest is a plain array literal in an ES module. Pull the array out
// rather than importing it, so this CommonJS script does not need ESM loading.
const source = fs.readFileSync(MANIFEST, "utf8");
const start = source.indexOf("[");
const end = source.lastIndexOf("]");
if (start === -1 || end === -1) throw new Error("could not locate the manifest array");

const entries = JSON.parse(source.slice(start, end + 1));
console.log(`manifest entries: ${entries.length}`);
console.log(`cloudinary mapping: ${Object.keys(mapping).length}\n`);

const rebuilt = [];
const missing = [];

for (const entry of entries) {
  const publicId = lookup(entry.url);
  if (!publicId) {
    missing.push(entry.url);
    continue;
  }
  const dims = mapping[String(entry.url).replace(/^\//, "")];
  rebuilt.push({
    publicId,
    width: dims.width,
    height: dims.height,
    originalPath: entry.originalPath,
    category: entry.category,
    model: entry.model,
    file: entry.file,
  });
}

console.log(`mapped:  ${rebuilt.length}`);
console.log(`missing: ${missing.length}`);

if (missing.length) {
  console.log("\nunmapped entries (manifest will NOT be written):");
  missing.slice(0, 10).forEach((u) => console.log(`  ${u}`));
  process.exit(1);
}

const output = `// GENERATED by Backend/scripts/rebuild-frontend-manifest.js — do not edit by hand.
//
// Each entry references a Cloudinary public_id, not a URL. The URL is built at
// render time by cloudinaryUrl(), so the cloud name and transformation string
// stay in one place and can change without touching this file.
//
// width/height are carried through so components can reserve layout space
// before the image loads, which is what prevents cumulative layout shift.
const productImageManifest = ${JSON.stringify(rebuilt, null, 4)};

export default productImageManifest;
`;

if (DRY_RUN) {
  console.log("\n--- first 2 rebuilt entries ---");
  console.log(JSON.stringify(rebuilt.slice(0, 2), null, 2));
  console.log("\n(dry run — nothing written)");
} else {
  fs.writeFileSync(MANIFEST, output);
  console.log(`\nwritten: ${MANIFEST}`);
  console.log(`size: ${(output.length / 1024).toFixed(0)} KB`);
}
